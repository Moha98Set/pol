def reason(code: str) -> Tuple[str, str]:
    """Label and explanation for a code, falling back to the raw code."""
    if code in REASONS:
        return REASONS[code]
    if code in SUSPICIONS:
        return SUSPICIONS[code]
    return (code, "توضیحی برای این کد ثبت نشده است.")


def reason_label(code: str) -> str:
    return reason(code)[0]


def stage_label(stage: str) -> str:
    return STAGES.get(stage, (stage, ""))[0]


def outcome_label(outcome: str) -> str:
    return OUTCOMES.get(outcome, outcome)
